#!/usr/bin/env python3
"""Build the BLOCK1-BLOCK19 picture files and the picture directory from src/pictures/.

usage: picfile.py build <src/pictures dir> <out dir> <pictures.inc out>
       picfile.py extract <extracted dir> <out src/pictures dir>   (used once to create the source)

Each src/pictures/blockNN.txt is one BLOCK file: its pictures in order, numbered across all
blocks. A picture is a list of line rows:

    picture 1
      line 14,7 253,7 253,149 13,149 13,7
      line 14,104 253,104

`line x,y x,y ...` starts a new line at the first point and draws to each following one; on
the disk it is the 00 00 marker followed by the points. `cont x,y ...` (no marker) continues
from wherever the pen was, which for the first row of a picture means the previous picture's
last point; picture 92 starts this way, and long rows are wrapped onto cont rows. Coordinates are 1-255 for x and 0-160 for y (0,0 cannot
be stored: it is the marker). The picture ends with FF FF on the disk. `leftover $xx,...` keeps
stale bytes found after the last picture of a block.

Pictures are drawn by draw_picture (src/adventure.s) at an object's position plus the point,
clamped to 255 x 160. The build writes each BLOCK file (BSAVEd at $4400, loaded by the engine
into a cache slot) and pictures.inc, the directory (block, offset per picture) that
src/adventure.s includes at $5300. Entry 0 is unused; it keeps the bytes found in the original.
A BLOCK file must fit a cache slot ($500 bytes).
"""
import os
import re
import sys

ENTRY0 = (0xC7, 0xCF, 0xA0)   # directory entry 0 in the original: stale text, never read
SLOT = 0x500


def parse_block(path, first_number):
    pics = []        # (number, bytes)
    tail = b''
    cur = None
    for n, line in enumerate(open(path, encoding='ascii'), 1):
        line = line.split(';')[0].strip()
        if not line:
            continue
        word, _, rest = line.partition(' ')
        if word == 'picture':
            if cur is not None:
                pics.append((cur[0], bytes(cur[1]) + b'\xff\xff'))
            num = int(rest)
            expect = first_number + len(pics)
            if num != expect:
                raise SystemExit('%s:%d: picture %d out of order (expected %d)' % (path, n, num, expect))
            cur = (num, bytearray())
        elif word in ('line', 'cont'):
            if cur is None:
                raise SystemExit('%s:%d: points before "picture"' % (path, n))
            if word == 'line':
                cur[1].extend(b'\x00\x00')
            for pt in rest.split():
                x, y = (int(v) for v in pt.split(','))
                if not (0 <= x <= 255 and 0 <= y <= 255) or (x, y) == (0, 0) or (x, y) == (255, 255):
                    raise SystemExit('%s:%d: point %s cannot be stored' % (path, n, pt))
                cur[1].extend((x, y))
        elif word == 'leftover':
            tail = bytes(int(v.strip().lstrip('$'), 16) for v in rest.split(','))
        else:
            raise SystemExit('%s:%d: unknown "%s"' % (path, n, word))
    if cur is not None:
        pics.append((cur[0], bytes(cur[1]) + b'\xff\xff'))
    return pics, tail


def build(srcdir, outdir, inc):
    os.makedirs(outdir, exist_ok=True)
    files = sorted(f for f in os.listdir(srcdir) if re.fullmatch(r'block\d\d\.txt', f))
    if len(files) > 19:
        raise SystemExit('the disk has BLOCK1-BLOCK19; adding a block file is not supported')
    directory = {}
    number = 1
    for k, f in enumerate(files, 1):
        if f != 'block%02d.txt' % k:
            raise SystemExit('expected block%02d.txt, found %s' % (k, f))
        pics, tail = parse_block(os.path.join(srcdir, f), number)
        data = bytearray()
        for num, stream in pics:
            directory[num] = (k, len(data))
            data += stream
        data += tail
        if len(data) > SLOT:
            raise SystemExit('BLOCK%d is %d bytes; a cache slot holds %d' % (k, len(data), SLOT))
        open(os.path.join(outdir, 'BLOCK%d.bin' % k), 'wb').write(data)
        number += len(pics)
    with open(inc, 'w') as f:
        f.write('; generated by tools/picfile.py from src/pictures/: do not edit\n')
        f.write('picture_directory:\n')
        f.write('        .byte $%02X, $%02X, $%02X   ; picture 0 (unused)\n' % ENTRY0)
        for num in range(1, number):
            b, o = directory[num]
            f.write('        .byte %d, <$%04X, >$%04X   ; picture %d\n' % (b, o, o, num))
    print('%d pictures in %d blocks' % (number - 1, len(files)))


def extract(ext, out):
    adv = open(os.path.join(ext, 'ADVENTURE.bin'), 'rb').read()
    entry = lambda n: (adv[0x5300 + 3 * n - 0x800], adv[0x5301 + 3 * n - 0x800] | adv[0x5302 + 3 * n - 0x800] << 8)
    os.makedirs(out, exist_ok=True)
    n = 1
    for b in range(1, 20):
        data = open(os.path.join(ext, 'BLOCK%d.bin' % b), 'rb').read()
        lines = ['; BLOCK%d: pictures in file order (see tools/picfile.py for the format)' % b]
        pos = 0
        while n <= 97 and entry(n)[0] == b:
            assert entry(n)[1] == pos, (b, n)
            lines += ['', 'picture %d' % n]
            row = None
            while (data[pos], data[pos + 1]) != (0xFF, 0xFF):
                x, y = data[pos], data[pos + 1]
                pos += 2
                if (x, y) == (0, 0):
                    if row is not None:
                        lines.append(row)
                    row = '  line'
                    continue
                if row is None:
                    row = '  cont'
                elif row.count(',') == 10:
                    lines.append(row)           # wrap long rows: a cont row adds no bytes
                    row = '  cont'
                row += ' %d,%d' % (x, y)
            if row is not None:
                lines.append(row)
            pos += 2
            n += 1
        if pos < len(data):
            lines += ['', 'leftover ' + ','.join('$%02X' % c for c in data[pos:])]
        open(os.path.join(out, 'block%02d.txt' % b), 'w').write('\n'.join(lines) + '\n')


def main():
    if sys.argv[1] == 'build':
        build(*sys.argv[2:5])
    elif sys.argv[1] == 'extract':
        extract(*sys.argv[2:4])
    else:
        raise SystemExit(__doc__)


if __name__ == '__main__':
    main()
