#!/usr/bin/env python3
"""Build the MESSAGES text file and its index from src/messages.txt.

usage: msgfile.py build <messages.txt> <MESSAGES out> <messages.inc out>
       msgfile.py extract <MESSAGES.txt.bin> <out messages.txt>     (used once to create the source)

messages.txt has one message per line, numbered from 1 in order:

    1 IT IS TOO HIGH
    2 OK

Lines starting with ';' are comments. A message with leading or trailing spaces is written in
double quotes (167 " "). Messages are upper case: the Apple II prints them as they are.

MESSAGES on the disk is a DOS text file: each message in high-bit ASCII ending with $8D (CR),
in number order, then a $00. The engine reads message n by byte offset (READ MESSAGES,B$xxxx);
messages.inc is the offset table (message_index) that src/adventure.s includes at $5500.
Entry 0 is unused; it keeps the value found in the original ($0006).
"""
import pathlib
import sys

INDEX0 = 0x0006


def parse(path):
    msgs = []
    for n, line in enumerate(pathlib.Path(path).read_text(encoding='ascii').splitlines(True), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith(';'):
            continue
        num, _, text = line.partition(' ')
        if not num.isdigit():
            raise SystemExit('%s:%d: expected "<number> <text>"' % (path, n))
        if int(num) != len(msgs) + 1:
            raise SystemExit('%s:%d: message %s out of order (expected %d)' % (path, n, num, len(msgs) + 1))
        if len(text) >= 2 and text.startswith('"') and text.endswith('"'):
            text = text[1:-1]
        for c in text:
            if not 0x20 <= ord(c) < 0x7F:
                raise SystemExit('%s:%d: character %r cannot be printed' % (path, n, c))
        msgs.append(text)
    return msgs


def build(src, out_file, out_inc):
    msgs = parse(src)
    data = bytearray()
    offsets = []
    for t in msgs:
        offsets.append(len(data))
        data += bytes(ord(c) | 0x80 for c in t) + b'\x8d'
    data.append(0)
    if len(data) > 0xFFFF:
        raise SystemExit('MESSAGES is larger than 64 KB')
    pathlib.Path(out_file).write_bytes(data)
    with open(out_inc, 'w') as f:
        f.write('; generated by tools/msgfile.py from src/messages.txt: do not edit\n')
        f.write('message_index:\n')
        f.write('        .word $%04X   ; 0 (unused)\n' % INDEX0)
        for i, (o, t) in enumerate(zip(offsets, msgs), 1):
            f.write('        .word $%04X   ; %d %s\n' % (o, i, t[:60]))
    print('%d messages, %d bytes' % (len(msgs), len(data)))


def extract(raw, out):
    msgs = []
    p = 0
    while raw[p]:
        e = raw.index(0x8D, p)
        msgs.append(bytes(b & 0x7F for b in raw[p:e]).decode('ascii'))
        p = e + 1
    with open(out, 'w') as f:
        f.write('; The game\'s messages, by number (see tools/msgfile.py for the format).\n'
                '; The engine prints message n with print_message (LDX #n); rules use A_MESSAGE, n.\n'
                '; Messages 7, 37, 127 and 137 are never shown: print_message prints its own\n'
                '; built-in text for those numbers (see print_message in src/adventure.s).\n')
        for i, t in enumerate(msgs, 1):
            f.write('%d %s\n' % (i, '"%s"' % t if t != t.strip() else t))


def main():
    if sys.argv[1] == 'build':
        build(*sys.argv[2:5])
    elif sys.argv[1] == 'extract':
        extract(pathlib.Path(sys.argv[2]).read_bytes(), sys.argv[3])
    else:
        raise SystemExit(__doc__)


if __name__ == '__main__':
    main()
